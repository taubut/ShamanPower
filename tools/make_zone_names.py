#!/usr/bin/env python3
"""Writes ShamanPowerZoneNames.lua: every dungeon, raid, battleground and arena name in each game's own data
(Map.db2: the map's name, and its own area's name from AreaTable.db2 when that differs), with its kind. The Zone
Name box of an Auto Loadout Group fills them in and suggests them: the game's world map (C_Map) has no page for
instances on these clients.

usage: make_zone_names.py FOREVER_DIR ANNIVERSARY_DIR   (each holding Map.db2 + AreaTable.db2, any case or the
       casc_read dump names dbfilesclient__map.db2 / dbfilesclient__areatable.db2)
Needs ~/.claude/shamanpower/casc-tools/wdc5.py and the WoWDBDefs Map.dbd / AreaTable.dbd (in DBD_DIR, default the
scratch db2 folder; set DBD_DIR to change it)."""
import json, os, re, subprocess, sys, tempfile

WDC5 = os.path.expanduser("~/.claude/shamanpower/casc-tools/wdc5.py")
DBD = os.environ.get("DBD_DIR", "/tmp/claude-1000/-home-taubut/7d4b814b-5452-4034-8a51-e8c814e0af75/scratchpad/db2")
KIND = {1: "party", 2: "raid", 3: "pvp", 4: "pvp"}
JUNK = re.compile(r"test|unused|^cashtest$|\*\*\*", re.I)

def find(d, table):
    for n in os.listdir(d):
        if n.lower() in (table.lower() + ".db2", "dbfilesclient__" + table.lower() + ".db2"):
            return os.path.join(d, n)
    sys.exit("no %s.db2 in %s" % (table, d))

def rows(d, table):
    out = tempfile.mktemp(suffix=".json")
    subprocess.run([sys.executable, WDC5, find(d, table), os.path.join(DBD, table + ".dbd"), "--json", out],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    r = json.load(open(out))
    os.remove(out)
    return r if isinstance(r, list) else r.get("rows", r)

def names(d):
    areas = {a["ID"]: a for a in rows(d, "AreaTable")}
    seen, out = set(), []
    for m in sorted(rows(d, "Map"), key=lambda m: m["ID"]):
        kind = KIND.get(m.get("InstanceType"))
        if not kind:
            continue
        cands = [m.get("MapName_lang") or ""]
        a = areas.get(m.get("AreaTableID"))
        if a:
            cands.append(a.get("AreaName_lang") or "")
        for n in cands:
            n = n.strip()
            if n and not JUNK.search(n) and n.lower() not in seen:
                seen.add(n.lower())
                out.append((n, kind))
    return sorted(out, key=lambda x: x[0].lower())

def lua_list(lst):
    return "\n".join('\t{ %s, "%s" },' % (json.dumps(n), k) for n, k in lst)

forever, anniv = names(sys.argv[1]), names(sys.argv[2])
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "..", "ShamanPowerZoneNames.lua"), "w") as f:
    f.write("-- Generated by tools/make_zone_names.py from each game's own Map.db2 and AreaTable.db2: the dungeon, raid,\n"
            "-- battleground and arena names an Auto Loadout Group's Zone Name box fills in and suggests (the game's world\n"
            "-- map has no page for them). A leading \"The\" never matters in a zone's name, so Molten Core here is The\n"
            "-- Molten Core inside. Each: { name, kind } (kind: \"raid\", \"party\" (a dungeon) or \"pvp\").\n"
            "local SP = ShamanPower\n"
            "if not SP then return end\n"
            "if SPCompat.FOREVER then\n"
            "SP.INSTANCE_NAMES = {\n" + lua_list(forever) + "\n}\n"
            "else\n"
            "SP.INSTANCE_NAMES = {\n" + lua_list(anniv) + "\n}\n"
            "end\n")
print("forever", len(forever), "anniversary", len(anniv))
